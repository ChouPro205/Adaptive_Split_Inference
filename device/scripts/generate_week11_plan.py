#!/usr/bin/env python3
"""Week 11 link plans (W11-D2, W11-D3) for the week 12 PPK2 sessions, written into a new --output directory:

  link_plan_s<k>.csv        session k (k = 0, 1): block, state, op, a, b per entry (week11_common.session_plan)
  week11_link_plan_s<k>.h   the state table + the entries + WEEK11_LINK_PLAN_SHA256 (firmware `link`, `link-usb`)
  echo_vectors.json         echo frames (ack and full mode) and the answer the KV260 must send for every W11-D2
                            size (request_id 0x01020304), for the KV260 echo service (SV2) to test against
  manifest.json             seeds, counts, digests and their definitions, SHA-256 of every output
The outputs are deterministic (manifest.json aside: it records time and git state). Host only.
Run: device\\host\\.venv\\Scripts\\python.exe -B device\\scripts\\generate_week11_plan.py --output <new dir>
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import week11_common as w11  # noqa: E402

VECTOR_RID = 0x01020304


def outputs() -> tuple:
    return tuple(n for k in range(w11.SESSIONS) for n in (f"link_plan_s{k}.csv", f"week11_link_plan_s{k}.h")) + (
        "echo_vectors.json",)


def header(rows, session: int, digest: str) -> str:
    s = w11.STATES
    lines = ["/* GENERATED by device/scripts/generate_week11_plan.py - do not edit.",
             f" * W11-D3 link session {session} (seed {w11.SESSION_SEED_BASE + session}): {len(s)} link-state blocks, base first,",
             " * then a random order; ops per block shuffled. op: 0 STATE, 1 IDLE (a = ms), 2 ECHO (a = frame",
             " * bytes, b bit 0 = ECHO-ACK v1, bit 1 = latency off during WAIT), 3 S0C (a = W8-D3 sample,",
             " * b = encodes per D0 pulse), 4 RECONNECT. phy: 1 = 1M, 2 = 2M, 3 = Coded S8. */",
             "#ifndef WEEK11_LINK_PLAN_H", "#define WEEK11_LINK_PLAN_H", "#include <stdint.h>",
             f"#define WEEK11_LINK_PLAN_SESSION {session}U",
             f"#define WEEK11_LINK_PLAN_SEED {w11.SESSION_SEED_BASE + session}U",
             f"#define WEEK11_LINK_STATES {len(s)}U", f"#define WEEK11_LINK_PLAN_ENTRIES {len(rows)}U",
             f"#define WEEK11_LINK_PLAN_BLOCKS {max(r.block for r in rows) + 1}U",
             f'#define WEEK11_LINK_PLAN_SHA256 "{digest}"',
             "/* SHA-256 input: per state (index, phy, interval, latency, timeout uint16 LE, tx_octets, tx_power_dbm",
             " * int8) = 10 bytes, then per entry (op, state, a uint16 LE, b uint16 LE) = 6 bytes. */",
             "struct week11_link_state { uint8_t index; uint8_t phy; uint16_t interval_1250us; uint16_t latency;",
             "\tuint16_t timeout_10ms; uint8_t tx_octets; int8_t tx_power_dbm; };",
             "struct week11_link_entry { uint8_t op; uint8_t state; uint16_t a; uint16_t b; };",
             "static const struct week11_link_state week11_link_states[WEEK11_LINK_STATES] = {"]
    for st in s:
        lines.append(f"\t{{{st.index}, {st.phy}, {st.interval_1250us}, {st.latency}, {st.timeout_10ms}, "
                     f"{st.tx_octets}, {st.tx_power_dbm}}},   /* {st.name} */")
    lines += ["};", "static const struct week11_link_entry week11_link_plan[WEEK11_LINK_PLAN_ENTRIES] = {"]
    for k in range(0, len(rows), 8):
        chunk = rows[k:k + 8]
        lines.append("\t" + ", ".join(f"{{{r.op}, {r.state}, {r.a}, {r.b}}}" for r in chunk) + ",")
    lines += ["};", "#endif", ""]
    return "\n".join(lines)


def vectors() -> dict:
    out = []
    for size in w11.ECHO_SIZES:
        for ack_mode in (True, False):
            frame = w11.echo_frame(size, VECTOR_RID, ack_mode)
            answer = w11.ack_frame(frame) if ack_mode else frame
            out.append({"length": size, "request_id": VECTOR_RID, "mode": "ack" if ack_mode else "full",
                        "frame_hex": frame.hex(), "frame_sha256": hashlib.sha256(frame).hexdigest(),
                        "answer_hex": answer.hex()})
    return {"schema": "week11-echo-vectors/2",
            "echo_frame": "I1 v2 envelope: magic I1PK, version 2, type 0x01, flags 0, header_length 32, "
                          "reserved_0 (uint16 LE, offset 10) = answer asked for (1 = ECHO-ACK v1, 0 = whole frame), "
                          "metadata 0, nonce 0, payload byte i = (i ^ (i >> 8) ^ request_id) & 0xff, CRC-32/ISO-HDLC",
            "ack_v1": "72 B I1 v2 envelope: type 0x02, request_id of the received frame, payload = uint32 LE "
                      "length of the received frame + SHA-256 of the received frame, CRC-32/ISO-HDLC; sent on "
                      "stream 0x02",
            "vectors": out}


def checks_for(rows) -> dict:
    blocks = {}
    for r in rows:
        blocks.setdefault(r.block, []).append(r)
    counts = Counter((r.state, r.op, r.a, r.b) for r in rows if r.op == w11.OP_ECHO)
    ok_echo = True
    for st in w11.STATES:
        variants = [w11.ECHO_ACK] if st.latency == 0 else [w11.ECHO_ACK, w11.ECHO_ACK | w11.ECHO_LATENCY_OFF]
        for size in w11.ECHO_SIZES:
            for flags in variants:
                ok_echo &= counts[(st.index, w11.OP_ECHO, size, flags)] == w11.ECHO_REPEATS
            want_full = w11.ECHO_FULL_REPEATS if st.index == w11.BASE else 0
            ok_echo &= counts[(st.index, w11.OP_ECHO, size, 0)] == want_full
    state_blocks = [b for b in sorted(blocks) if b < len(w11.STATES)]
    return {
        "one_block_per_state": sorted(blocks[b][0].state for b in state_blocks) == [s.index for s in w11.STATES],
        "base_block_first": blocks[0][0].state == w11.BASE,
        "every_block_state_idle_first_idle_last": all(
            [r.op for r in blocks[b][:2]] == [w11.OP_STATE, w11.OP_IDLE] and blocks[b][-1].op == w11.OP_IDLE
            and all(r.state == blocks[b][0].state for r in blocks[b]) for b in state_blocks),
        "echo_counts": ok_echo,
        "s0c_only_base": Counter((r.a, r.b) for r in rows if r.op == w11.OP_S0C)
                         == Counter({(n, k): 1 for n in range(w11.S0C_SAMPLES) for k in w11.S0C_REPEATS})
                         and all(r.state == w11.BASE for r in rows if r.op == w11.OP_S0C),
        "reconnects_last_block_base": [r.op for r in blocks[len(w11.STATES)]]
                                      == [w11.OP_STATE] + [w11.OP_RECONNECT] * w11.RECONNECTS + [w11.OP_IDLE]
                                      and all(r.state == w11.BASE for r in blocks[len(w11.STATES)]),
        "entries_fit_uint16": all(0 <= r.a <= 0xFFFF and 0 <= r.b <= 0xFFFF for r in rows),
        "echo_sizes_in_binding_limits": all(w11.FRAME_MIN <= r.a <= w11.FRAME_MAX for r in rows if r.op == w11.OP_ECHO),
        "index_is_position": all(r.index == i for i, r in enumerate(rows)),
    }


def git_state() -> dict:
    def run(*args):
        return subprocess.run(["git", *args], cwd=w11.ROOT, capture_output=True, text=True, check=True).stdout.strip()
    sources = [p.relative_to(w11.ROOT).as_posix() for p in
               (Path(__file__).resolve(), HERE / "week11_common.py", HERE / "week10_common.py", HERE / "week9_common.py")]
    return {"head": run("rev-parse", "HEAD"), "status_of_generator_sources": run("status", "--short", "--", *sources)}


def generate(output: Path) -> dict:
    if output.exists():
        raise SystemExit("Use a new output directory")
    output.mkdir(parents=True)
    sessions, checks = {}, {}
    for k in range(w11.SESSIONS):
        rows = w11.session_plan(k)
        digest = w11.sha256_hex(w11.plan_bytes(rows))
        w11.write_csv(output / f"link_plan_s{k}.csv", rows)
        (output / f"week11_link_plan_s{k}.h").write_bytes(header(rows, k, digest).encode("utf-8"))
        for name, ok in checks_for(rows).items():
            checks[f"s{k}_{name}"] = ok
        checks[f"s{k}_csv_read_back"] = w11.read_csv(output / f"link_plan_s{k}.csv") == rows
        sessions[f"s{k}"] = {"seed": w11.SESSION_SEED_BASE + k, "entries": len(rows), "plan_sha256": digest,
                             "block_order": [w11.STATES[r.state].name for r in rows if r.op == w11.OP_STATE],
                             "ops": dict(Counter(w11.OP_NAMES[r.op] for r in rows))}
    checks["sessions_differ_in_block_order"] = len({tuple(v["block_order"]) for v in sessions.values()}) == w11.SESSIONS
    vec = vectors()
    checks["vectors_answers_check"] = all(
        (w11.check_ack(bytes.fromhex(v["answer_hex"]), bytes.fromhex(v["frame_hex"])) if v["mode"] == "ack"
         else v["answer_hex"] == v["frame_hex"])
        and w11.echo_wants_ack(bytes.fromhex(v["frame_hex"])) == (v["mode"] == "ack") for v in vec["vectors"])
    (output / "echo_vectors.json").write_text(json.dumps(vec, indent=1) + "\n", encoding="utf-8")
    status = "PASS" if all(checks.values()) else "FAIL"
    manifest = {
        "schema": "week11-plan/1", "status": status, "decisions": ["W11-D2", "W11-D3"],
        "generator": "week11_common: splitmix64 + Fisher-Yates (week9_common), rejection sampling, one stream per session",
        "states": [s.__dict__ for s in w11.STATES],
        "echo_sizes": list(w11.ECHO_SIZES), "echo_repeats": w11.ECHO_REPEATS,
        "echo_full_repeats_base": w11.ECHO_FULL_REPEATS, "idle_ms": w11.IDLE_MS,
        "s0c": {"samples": w11.S0C_SAMPLES, "repeats": list(w11.S0C_REPEATS)}, "reconnects": w11.RECONNECTS,
        "plan_sha256_definition": "SHA-256 of the state table (10 B per state: index, phy, interval, latency, "
                                  "timeout uint16 LE, tx_octets, tx_power_dbm int8) + (op, state, a, b uint16 LE) "
                                  "per entry",
        "sessions": sessions, "checks": checks,
        "outputs_sha256": {n: hashlib.sha256((output / n).read_bytes()).hexdigest() for n in outputs()},
        "git": git_state(), "created_utc": datetime.now(timezone.utc).isoformat(),
    }
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", type=Path, required=True, help="new directory")
    manifest = generate(parser.parse_args().output.resolve())
    for name, ok in manifest["checks"].items():
        print(f"{'PASS' if ok else 'FAIL'} {name}")
    for k, v in manifest["sessions"].items():
        print(f"{k}: entries={v['entries']} plan_sha256={v['plan_sha256']} ops={v['ops']}")
        print(f"    blocks: {' '.join(v['block_order'])}")
    print(f"RESULT: {manifest['status']}")
    return 0 if manifest["status"] == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
