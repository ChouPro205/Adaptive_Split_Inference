#!/usr/bin/env python3
"""Generate the week 6 firmware vector tables from authenticated inputs.

Inputs: the SV3 50-vector P1 package (manifest SHA-256 must equal the trusted value from the
handoff receipt; every file hash and the exact inventory are checked first) and
contracts/i1v2_ref/vectors.json (goldens, boundary and response vectors). Writes
week6_vectors.h/.c and week6_build.h into a NEW directory. The public key 00..1f is
PUBLIC_TEST_ONLY and is only used by the on-device self tests, never by loopback I2/1.
Exit 0 on success; any authentication or consistency problem aborts.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REF = ROOT / "contracts" / "i1v2_ref"
sys.path.insert(0, str(REF))
import i1v2_reference as ref  # noqa: E402

PACKAGE_ID = "mitdb-week6-p1-50-20261016-v1"
REGISTRY = ROOT / "contracts" / "sv3_week5_approved_registry_v2.json"
TEST_PROFILE = ref.Profile(1, 1, frozenset({1}), {1: ref.Split(1, 0, 64, 90, True)}, 5760, 64, 6380)
SENDER_ID = 131073


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def verify_package(package: Path, expected_manifest: str) -> dict:
    manifest_path = package / "manifest.json"
    raw = manifest_path.read_bytes()
    if sha256(raw) != expected_manifest:
        sys.exit(f"FAIL manifest SHA-256 {sha256(raw)} != trusted {expected_manifest}")
    manifest = json.loads(raw)
    listed = {}
    for entry in manifest["files"]:
        rel = entry["path"]
        if rel.startswith(("/", "\\")) or ".." in Path(rel).parts:
            sys.exit(f"FAIL unsafe path in manifest: {rel}")
        listed[rel] = entry
    present = {}
    for path in package.rglob("*"):
        if path.is_symlink():
            sys.exit(f"FAIL symlink in package: {path}")
        if path.is_file() and path != manifest_path:
            present[path.relative_to(package).as_posix()] = path
    if set(present) != set(listed):
        sys.exit(f"FAIL inventory differs: missing={sorted(set(listed) - set(present))} "
                 f"extra={sorted(set(present) - set(listed))}")
    for rel, entry in listed.items():
        data = present[rel].read_bytes()
        if len(data) != entry["size_bytes"] or sha256(data) != entry["sha256"]:
            sys.exit(f"FAIL file hash/size: {rel}")
    return manifest


def fp16_to_fp32_bits(bits16: int) -> int:
    exponent = (bits16 >> 10) & 0x1F
    if bits16 >> 15 or exponent == 0 or exponent == 0x1F:
        raise ValueError(f"scale {bits16:#06x} is not a positive normal FP16")
    value = struct.unpack("<e", struct.pack("<H", bits16))[0]
    out = struct.unpack("<I", struct.pack("<f", value))[0]
    assert out & 0x1FFF == 0 and ref.scale_is_fp16_normal(out)
    return out


def float_bits(values) -> list:
    return [struct.unpack("<I", struct.pack("<f", v))[0] for v in values]


def c_bytes(data: bytes, per_line: int = 16) -> str:
    rows = []
    for i in range(0, len(data), per_line):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + per_line]) + ",")
    return "\n".join(rows) if rows else "    0,"


def c_words(words, per_line: int = 8) -> str:
    rows = []
    for i in range(0, len(words), per_line):
        rows.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i + per_line]) + ",")
    return "\n".join(rows)


def c_digest(hex_digest: str) -> str:
    return "{" + ", ".join(f"0x{hex_digest[i:i + 2]}" for i in range(0, 64, 2)) + "}"


HEADER = """/* GENERATED by device/scripts/generate_week6_vectors.py - do not edit. */
#ifndef WEEK6_VECTORS_H
#define WEEK6_VECTORS_H

#include <stddef.h>
#include <stdint.h>

#define W6_PACKAGE_ID "{package_id}"
#define W6_PACKAGE_MANIFEST_SHA256 "{manifest}"
#define W6_I1V2_VECTORS_SHA256 "{vectors}"
#define W6_VECTOR_COUNT {count}u
#define W6_GOLDEN_COUNT {goldens}u
#define W6_RESPONSE_CASE_COUNT {responses}u

/* SV3 P1 vector: real INT8 q [1,C,L], FP16 scales expanded exactly to FP32 bits. */
struct w6_vector {{
    uint8_t index;
    uint8_t s;
    uint16_t split_id;
    uint16_t channels;
    uint16_t length;
    uint32_t request_id;
    uint32_t sequence;
    uint16_t request_length;
    const int8_t *q;
    const uint32_t *scale_bits;
    uint8_t descriptor_sha256[32];
    uint8_t transformed_sha256[32];
    uint8_t request_sha256[32];
}};

/* contracts/i1v2_ref/vectors.json request golden/boundary (PUBLIC_TEST_ONLY key). */
struct w6_golden {{
    const char *id;
    uint32_t model_profile_id;
    uint32_t request_id;
    uint32_t key_id;
    uint16_t split_id;
    uint16_t channels;
    uint32_t length;
    const int8_t *q;
    const uint32_t *scale_bits;
    const uint8_t *nonce;      /* NULL for a plain request */
    uint16_t frame_length;
    uint8_t sha256[32];
}};

/* Device response check (I1 v2 §8.3); expected_kind 0 = drop, 1 = OK, 2 = ERROR_RESPONSE. */
struct w6_response_case {{
    const char *id;
    const uint8_t *packet;
    uint16_t length;
    uint32_t expected_request_id;
    uint8_t expected_kind;
    uint16_t expected_status;
}};

extern const uint8_t w6_public_key[32];
extern const struct w6_vector w6_vectors[W6_VECTOR_COUNT];
extern const struct w6_golden w6_goldens[W6_GOLDEN_COUNT];
extern const struct w6_response_case w6_response_cases[W6_RESPONSE_CASE_COUNT];

#endif
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--package", type=Path,
                        default=ROOT / "ml" / "artifacts" / "week6" / PACKAGE_ID)
    parser.add_argument("--expected-manifest-sha256", required=True)
    parser.add_argument("--build-id", required=True)
    parser.add_argument("--variant", required=True, choices=["default", "mtu23"])
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    if args.output.exists():
        sys.exit(f"refusing to overwrite {args.output}")

    verify_package(args.package, args.expected_manifest_sha256)
    package = json.loads((args.package / "vectors.json").read_text(encoding="utf-8"))
    vectors_raw = (REF / "vectors.json").read_bytes()
    contract = json.loads(vectors_raw)
    key = bytes.fromhex(package["key_hex"])
    if key != bytes.fromhex(contract["public_test_key_hex"]) or key != bytes(range(32)):
        sys.exit("FAIL package key is not the PUBLIC_TEST_ONLY key 00..1f")
    registry = ref.load_profile(REGISTRY)

    body = ["/* GENERATED by device/scripts/generate_week6_vectors.py - do not edit. */",
            '#include "week6_vectors.h"', "",
            "/* PUBLIC_TEST_ONLY (I1 v2 §12): self tests only, never a bench key. */",
            "const uint8_t w6_public_key[32] = {", c_bytes(key), "};", ""]
    rows = []
    vectors = sorted(package["vectors"], key=lambda v: int(v["vector_index"]))
    if [int(v["vector_index"]) for v in vectors] != list(range(50)):
        sys.exit("FAIL expected vector_index 0..49")
    for v in vectors:
        i = int(v["vector_index"])
        files = {k: (args.package / p).read_bytes() for k, p in v["files"].items()}
        shape = json.loads(v["shape"]) if isinstance(v["shape"], str) else v["shape"]
        n, channels, length = shape
        split = registry.splits[int(v["wire_split_id"])]
        if (n, channels, length) != (1, split.channels, split.length) or len(files["q"]) != channels * length:
            sys.exit(f"FAIL vector {i}: shape/registry mismatch")
        if 0x80 in files["q"]:
            sys.exit(f"FAIL vector {i}: q contains -128")
        sequence = int(v["sequence"])
        if files["nonce"] != struct.pack("<IQ", SENDER_ID, sequence) or int(v["sender_id"]) != SENDER_ID:
            sys.exit(f"FAIL vector {i}: nonce rule")
        scales16 = struct.unpack(f"<{channels}H", files["scale"])
        scale_bits = [fp16_to_fp32_bits(b) for b in scales16]
        request = ref.parse_request(files["request"], registry)
        if request.request_id != int(v["request_id"]) or float_bits(request.scales) != scale_bits:
            sys.exit(f"FAIL vector {i}: request.i1v2.bin disagrees with q/scale files")
        body += [f"static const uint8_t q{i}[{len(files['q'])}] = {{",
                 c_bytes(files["q"]), "};",
                 f"static const uint32_t scale{i}[{channels}] = {{", c_words(scale_bits), "};"]
        rows.append(
            f"    {{{i}u, {int(v['split_point_s'])}u, {int(v['wire_split_id'])}u, {channels}u, {length}u, "
            f"{int(v['request_id'])}u, {sequence}u, {len(files['request'])}u, (const int8_t *)q{i}, scale{i},\n"
            f"     {c_digest(sha256(files['descriptor']))},\n"
            f"     {c_digest(sha256(files['transformed']))},\n"
            f"     {c_digest(sha256(files['request']))}}},")
    body += ["", "const struct w6_vector w6_vectors[W6_VECTOR_COUNT] = {"] + rows + ["};", ""]

    goldens = []
    cases = [("plain_s10", contract["golden"]["plain_s10"], registry),
             ("i2_s10", contract["golden"]["i2_s10"], registry)]
    for b in contract["boundary"]:
        cases.append((b["id"], b, registry if b["profile"] == "registry" else TEST_PROFILE))
    for g, (name, case, profile) in enumerate(cases):
        packet = bytes.fromhex(case["packet_hex"])
        r = ref.parse_request(packet, profile)
        q = bytes.fromhex(case["q_hex"])
        key_id = struct.unpack_from("<I", r.descriptor, 20)[0] if r.transformed else 0
        body += [f"static const uint8_t gq{g}[{len(q)}] = {{", c_bytes(q), "};",
                 f"static const uint32_t gscale{g}[{r.split.channels}] = {{",
                 c_words(float_bits(r.scales)), "};"]
        nonce_ref = "NULL"
        if r.transformed:
            body += [f"static const uint8_t gnonce{g}[12] = {{", c_bytes(r.nonce), "};"]
            nonce_ref = f"gnonce{g}"
        goldens.append(
            f'    {{"{name}", {r.model_profile_id}u, {r.request_id}u, {key_id}u, {r.split.split_id}u, '
            f"{r.split.channels}u, {r.split.length}u, (const int8_t *)gq{g}, gscale{g}, {nonce_ref}, {len(packet)}u,\n"
            f"     {c_digest(sha256(packet))}}},")
    body += ["", "const struct w6_golden w6_goldens[W6_GOLDEN_COUNT] = {"] + goldens + ["};", ""]

    responses = []
    for r_i, case in enumerate(contract["response"]):
        packet = bytes.fromhex(case["packet_hex"])
        try:
            kind_name, value = ref.parse_response(packet, case["expected_request_id"], 6380)
            kind, status = (1, 0) if kind_name == "OK" else (2, value)
        except ref.Drop:
            kind, status = 0, 0
        if ["DROP", "OK", "ERROR"][kind] != case["expected"]:
            sys.exit(f"FAIL response vector {case['id']} disagrees with the reference")
        body += [f"static const uint8_t resp{r_i}[{len(packet)}] = {{", c_bytes(packet), "};"]
        responses.append(f'    {{"{case["id"]}", resp{r_i}, {len(packet)}u, {case["expected_request_id"]}u, '
                         f"{kind}u, {status}u}},")
    body += ["", "const struct w6_response_case w6_response_cases[W6_RESPONSE_CASE_COUNT] = {"] + \
        responses + ["};", ""]

    args.output.mkdir(parents=True)
    (args.output / "week6_vectors.h").write_bytes(HEADER.format(
        package_id=PACKAGE_ID, manifest=args.expected_manifest_sha256, vectors=sha256(vectors_raw),
        count=len(rows), goldens=len(goldens), responses=len(responses)).encode())
    (args.output / "week6_vectors.c").write_bytes(("\n".join(body) + "\n").encode())
    (args.output / "week6_build.h").write_bytes(
        ("/* GENERATED by device/scripts/generate_week6_vectors.py - do not edit. */\n"
         "#ifndef WEEK6_BUILD_H\n#define WEEK6_BUILD_H\n"
         f'#define WEEK6_BUILD_ID "{args.build_id}"\n#define WEEK6_VARIANT "{args.variant}"\n'
         "#endif\n").encode())
    print(f"PASS package {PACKAGE_ID} manifest {args.expected_manifest_sha256}; {len(rows)} vectors, "
          f"{len(goldens)} goldens, {len(responses)} response cases -> {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
