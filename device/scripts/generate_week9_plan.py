#!/usr/bin/env python3
"""Week 9 session order (W9-D4): 50 rounds x 11 splits = 550 E_dev cycles.

Round k uses W8-D3 sample k (W9-D3) at the 11 splits in a random permutation, so drift in
temperature or time is spread over every s instead of following it. The permutation generator is
week9_common.plan_splits() (splitmix64 + Fisher-Yates, seed 20261103), reproducible without NumPy
or a particular Python version.

Writes into a new --output directory:
  plan.csv       cycle, round, sample, split (550 rows, cycle order)
  week9_plan.h   the 550 splits as a uint8_t array + WEEK9_PLAN_SHA256 (firmware, build_week9.ps1)
  manifest.json  seed, counts per split, SHA-256 of the 550 split bytes and of every output
The outputs are deterministic (manifest.json aside: it records time and git state).
Host only; no device access.
Run: device\\host\\.venv\\Scripts\\python.exe -B device\\scripts\\generate_week9_plan.py --output <new dir>
"""
from __future__ import annotations

import argparse
import csv
import json
import subprocess
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import week9_common as w9  # noqa: E402


def header(splits: list, digest: str) -> str:
    lines = ["/* GENERATED by device/scripts/generate_week9_plan.py - do not edit.",
             f" * W9-D4: {w9.ROUNDS} rounds x {w9.SPLITS} splits; cycle i = {w9.SPLITS} * k + j uses W8-D3 sample k",
             f" * at split week9_plan_split[i] (per round a permutation of 0..10, seed {w9.PLAN_SEED}). */",
             "#ifndef WEEK9_PLAN_H", "#define WEEK9_PLAN_H", "#include <stdint.h>",
             f"#define WEEK9_PLAN_SEED {w9.PLAN_SEED}U", f"#define WEEK9_PLAN_ROUNDS {w9.ROUNDS}U",
             f"#define WEEK9_PLAN_SPLITS {w9.SPLITS}U", f"#define WEEK9_PLAN_CYCLES {len(splits)}U",
             f'#define WEEK9_PLAN_SHA256 "{digest}"',
             "static const uint8_t week9_plan_split[WEEK9_PLAN_CYCLES] = {"]
    for k in range(w9.ROUNDS):
        row = splits[k * w9.SPLITS:(k + 1) * w9.SPLITS]
        lines.append("    " + ", ".join(f"{s:2d}" for s in row) + f",   /* round {k} */")
    lines += ["};", "#endif", ""]
    return "\n".join(lines)


def git_state() -> dict:
    def run(*args):
        return subprocess.run(["git", *args], cwd=w9.ROOT, capture_output=True, text=True, check=True).stdout.strip()
    sources = [p.relative_to(w9.ROOT).as_posix() for p in (Path(__file__).resolve(), HERE / "week9_common.py")]
    return {"head": run("rev-parse", "HEAD"), "status_of_generator_sources": run("status", "--short", "--", *sources)}


def generate(output: Path) -> dict:
    if output.exists():
        raise SystemExit("Use a new output directory")
    splits = w9.plan_splits()
    rows = w9.plan_rows(splits)
    digest = w9.plan_sha256(splits)
    per_split = Counter(splits)
    checks = {
        "cycles_550": len(splits) == w9.CYCLES,
        "every_round_a_permutation": all(sorted(splits[k * w9.SPLITS:(k + 1) * w9.SPLITS]) == list(range(w9.SPLITS))
                                         for k in range(w9.ROUNDS)),
        "50_cycles_per_split": all(per_split[s] == w9.ROUNDS for s in range(w9.SPLITS)),
        "round_k_uses_sample_k": all(r[1] == r[2] == r[0] // w9.SPLITS for r in rows),
    }
    output.mkdir(parents=True)
    with (output / "plan.csv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["cycle", "round", "sample", "split"])
        writer.writerows(rows)
    (output / "week9_plan.h").write_bytes(header(splits, digest).encode("utf-8"))
    checks["csv_reads_back"] = w9.read_plan_csv(output / "plan.csv") == rows
    status = "PASS" if all(checks.values()) else "FAIL"
    manifest = {
        "schema": "week9-plan/1",
        "status": status,
        "decision": "W9-D4",
        "seed": w9.PLAN_SEED,
        "generator": "week9_common.plan_splits: splitmix64 + Fisher-Yates per round (j = 10..1, rejection sampling)",
        "rounds": w9.ROUNDS,
        "splits": w9.SPLITS,
        "cycles": len(splits),
        "plan_sha256": digest,
        "plan_sha256_definition": "SHA-256 of the 550 split bytes in cycle order",
        "cycles_per_split": {str(s): per_split[s] for s in range(w9.SPLITS)},
        "first_rounds": [splits[k * w9.SPLITS:(k + 1) * w9.SPLITS] for k in range(3)],
        "checks": checks,
        "outputs_sha256": {n: w9.w8.w7.sha256_file(output / n) for n in ("plan.csv", "week9_plan.h")},
        "git": git_state(),
        "created_utc": datetime.now(timezone.utc).isoformat(),
    }
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", type=Path, required=True, help="new directory")
    manifest = generate(parser.parse_args().output.resolve())
    for name, ok in manifest["checks"].items():
        print(f"{'PASS' if ok else 'FAIL'} {name}")
    print(f"plan_sha256={manifest['plan_sha256']}")
    print(f"outputs_sha256={json.dumps(manifest['outputs_sha256'])}")
    print(f"RESULT: {manifest['status']}")
    return 0 if manifest["status"] == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
