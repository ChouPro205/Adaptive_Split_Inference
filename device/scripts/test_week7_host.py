#!/usr/bin/env python3
"""Host tests of the week 7 firmware modules and laptop tools (no dongle).

1. TC7 host part: device/week7/head_fast.c (optimized FP32) equals src/week4_head.c bit for bit
   on 20 samples x 11 splits, plus an interleaved sample/split sequence (no state leaks between
   calls or kernels). gcc on PATH or CC, -O2 -ffp-contract=off -fno-fast-math.
2. week7_common.py: the TC4 reference (request bytes built by contracts/i1v2_ref + i2_ref from the
   SV3 quantization20 golden q/scale) and the stub edge request handling (CRC/header, sequence
   rule, sample identification by q, unprotect with the key, response frame) against
   contracts/i1v2_ref vectors.
Host evidence only: not MCU, radio or power evidence.
Run: device\\host\\.venv\\Scripts\\python.exe -B device\\scripts\\test_week7_host.py
"""
from __future__ import annotations

import ctypes
import hashlib
import os
import shutil
import struct
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
import week7_common as w7  # noqa: E402

WEEK7 = ROOT / "device" / "week7"
SRC = ROOT / "device" / "src"
GENERATED = ROOT / "device" / "generated"
R3_FIRMWARE = ROOT / "ml" / "results" / "week4-r3" / "firmware"
TMP = Path(tempfile.mkdtemp(prefix="week7_host_"))
COUNTS = [360, 5760, 2880, 5760, 2880, 4320, 2160, 2880, 1408, 32, 5]
MIXED = [(3, 10), (0, 0), (19, 5), (7, 2), (12, 8), (5, 1), (19, 10), (0, 3),
         (8, 6), (14, 4), (2, 9), (11, 7), (17, 2), (6, 10), (9, 0), (1, 5)]


def build_head_library() -> ctypes.CDLL:
    cc = os.environ.get("CC") or shutil.which("gcc")
    if not cc:
        raise unittest.SkipTest("gcc not found (set CC)")
    for path in (GENERATED / "week4_graph.h", GENERATED / "week4_inputs.h",
                 R3_FIRMWARE / "head_parameters.h"):
        if not path.exists():
            raise unittest.SkipTest(f"missing {path} (generated by build_week4_head.ps1)")
    # A loaded DLL cannot be overwritten on Windows: one file per build.
    out = Path(tempfile.mkdtemp(dir=TMP)) / ("head_shim.dll" if os.name == "nt" else "head_shim.so")
    cmd = [cc, "-std=c11", "-O2", "-ffp-contract=off", "-fno-fast-math", "-shared", "-fPIC",
           "-Wall", "-Wextra", "-Werror", "-Wno-unknown-pragmas",
           "-I", str(WEEK7), "-I", str(SRC), "-I", str(GENERATED), "-I", str(R3_FIRMWARE),
           "-o", str(out), str(WEEK7 / "host_test" / "head_shim.c"), str(WEEK7 / "head_fast.c")]
    subprocess.run(cmd, check=True)
    lib = ctypes.CDLL(str(out))
    lib.shim_run.argtypes = [ctypes.c_int, ctypes.c_uint, ctypes.c_uint,
                             ctypes.POINTER(ctypes.c_uint32), ctypes.c_uint]
    return lib


class HeadFast(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.lib = build_head_library()
        cls.buf = (ctypes.c_uint32 * 5760)()

    def run_kernel(self, kernel, sample, split):
        n = self.lib.shim_run(kernel, sample, split, self.buf, 5760)
        self.assertEqual(n, COUNTS[split])
        return bytes(memoryview(self.buf).cast("B")[:4 * n])

    def test_bitwise_220(self):
        for sample in range(20):
            for split in range(11):
                ref = self.run_kernel(0, sample, split)
                fast = self.run_kernel(1, sample, split)
                self.assertEqual(ref, fast, f"sample {sample} split {split}")

    def test_interleaved_16(self):
        expected = {}
        for sample, split in MIXED:
            expected[(sample, split)] = self.run_kernel(0, sample, split)
        for i, (sample, split) in enumerate(MIXED):
            self.assertEqual(self.run_kernel(i % 2, sample, split), expected[(sample, split)])

    def test_s10_logits_match_r3_reference(self):
        # s=10 is the full model: FP32 logits of sample 0 differ from the INT8/FP16 reference
        # only by quantization; argmax must agree (sanity check that the right graph ran).
        logits = struct.unpack("<5f", self.run_kernel(1, 0, 10))
        reference = w7.reference_logits(0, 2)
        self.assertEqual(max(range(5), key=logits.__getitem__),
                         max(range(5), key=reference.__getitem__))

    def test_invalid_arguments(self):
        self.assertEqual(self.lib.shim_run(1, 0, 11, self.buf, 5760), -1)
        self.assertEqual(self.lib.shim_run(1, 20, 0, self.buf, 5760), -1)


def write_head_hashes(path: Path) -> None:
    """sha256 of the week 4 kernel output (FP32 LE bytes) for every (sample, split), for
    check_week7.py bench (MCU vs host). Same arithmetic, so the hashes must agree."""
    lib = build_head_library()
    buf = (ctypes.c_uint32 * 5760)()
    lines = ["sample,split,count,sha256"]
    for sample in range(20):
        for split in range(11):
            n = lib.shim_run(0, sample, split, buf, 5760)
            data = bytes(memoryview(buf).cast("B")[:4 * n])
            lines.append(f"{sample},{split},{n},{hashlib.sha256(data).hexdigest()}")
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")


class Reference(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        if not w7.QUANT20.exists():
            raise unittest.SkipTest("SV3 quantization20 package not hydrated")

    def test_golden_hashes(self):
        for sample in range(20):
            for split in (0, 2, 7, 10):
                golden = w7.golden_tensor(sample, split)
                self.assertEqual(hashlib.sha256(golden.q).hexdigest(), golden.q_sha256)
                self.assertEqual(hashlib.sha256(golden.scale_le).hexdigest(), golden.scale_sha256)

    def test_request_matches_p1_package(self):
        # The SV3 P1 package vector 10 is s=2 sample 0 with sequence 11 and request_id 11.
        if not w7.P1_PACKAGE.exists():
            self.skipTest("P1 package not hydrated")
        frame = w7.build_request(sample=0, split=2, request_id=11, key=w7.PUBLIC_TEST_KEY,
                                 sequence=11)
        expected = (w7.P1_PACKAGE / "vectors" / "010_s2_sample00" / "request.i1v2.bin").read_bytes()
        self.assertEqual(frame, expected)

    def test_plain_request_parses(self):
        frame = w7.build_request(sample=4, split=2, request_id=77, key=None, sequence=None)
        request = w7.ref.parse_request(frame, w7.registry_profile())
        self.assertEqual(request.request_id, 77)
        self.assertFalse(request.transformed)
        self.assertEqual(request.payload, w7.golden_tensor(4, 2).q)


class StubEdge(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        if not w7.QUANT20.exists():
            raise unittest.SkipTest("SV3 quantization20 package not hydrated")

    def test_p1_and_p0_requests(self):
        key = bytes(range(32))
        edge = w7.StubEdge(split=2, key=key)
        for i in range(4):
            rho_p1 = i < 2
            frame = w7.build_request(sample=i, split=2, request_id=100 + i,
                                     key=key if rho_p1 else None,
                                     sequence=500 + i if rho_p1 else None)
            response, record = edge.handle(frame)
            self.assertEqual(record["result"], "OK", record)
            self.assertEqual(record["sample"], i)
            self.assertEqual(record["rho"], "P1" if rho_p1 else "P0")
            kind, logits = w7.ref.parse_response(response, 100 + i, 6380)
            self.assertEqual(kind, "OK")
            self.assertEqual(len(response), 64)
            self.assertEqual(struct.pack("<5f", *logits),
                             struct.pack("<5f", *w7.reference_logits(i, 2)))
        self.assertEqual(edge.counters["response_sent"], 4)

    def test_rejections(self):
        key = bytes(range(32))
        edge = w7.StubEdge(split=2, key=key)
        good = w7.build_request(sample=1, split=2, request_id=5, key=key, sequence=10)
        bad_crc = bytearray(good)
        bad_crc[-1] ^= 1
        _, record = edge.handle(bytes(bad_crc))
        self.assertEqual(record["result"], "CRC_FAIL")
        edge.handle(good)
        _, record = edge.handle(w7.build_request(sample=1, split=2, request_id=6, key=key,
                                                 sequence=10))
        self.assertEqual(record["result"], "SEQUENCE_NOT_INCREASING")
        _, record = edge.handle(w7.build_request(sample=1, split=3, request_id=7, key=None,
                                                 sequence=None))
        self.assertEqual(record["result"], "WRONG_SPLIT")
        wrong_key = bytes([7] * 32)
        response, record = edge.handle(w7.build_request(sample=1, split=2, request_id=8,
                                                        key=wrong_key, sequence=11))
        # Wrong key: the recovered q is garbage (often contains -128, rejected by the reference).
        self.assertIsNone(response)
        self.assertIn(record["result"], {"UNKNOWN_Q", "REJECT_12"})
        self.assertEqual(edge.counters["crc_fail"], 1)
        self.assertEqual(edge.counters["response_sent"], 1)


class StubPeerOffline(unittest.TestCase):
    """week7_stub_edge.StubPeer.handle() without a radio: frames in, response frames out."""

    @classmethod
    def setUpClass(cls):
        if not w7.QUANT20.exists():
            raise unittest.SkipTest("SV3 quantization20 package not hydrated")

    def test_session_of_four(self):
        import asyncio
        import week7_stub_edge as stub
        key = bytes(range(32))
        peer = stub.StubPeer(TMP / "peer.jsonl", w7.StubEdge(2, key), expect=4)
        sent = []

        async def fake_send(frame, stream, label="reply"):
            sent.append((stream, frame))
        peer.send_frame = fake_send
        frames = [w7.build_request(i, 2, 1000 + i, key if i < 2 else None, 40 + i if i < 2 else None)
                  for i in range(4)]

        async def drive():
            for frame in frames:
                await peer.handle(stub.ble.STREAM_I1, frame)
            await peer.handle(stub.ble.STREAM_DIAG_ECHO, frames[0])   # wrong stream: ignored
        asyncio.run(drive())
        peer.close()
        self.assertTrue(peer.done.is_set())
        self.assertEqual(len(sent), 4)
        result = stub.evaluate(peer.records, peer.edge.counters, 2, 2)
        self.assertEqual(result["status"], "PASS", result)
        self.assertEqual(result["first_sequence"], 40)
        bad = stub.evaluate(peer.records[:3], peer.edge.counters, 2, 2)
        self.assertEqual(bad["status"], "FAIL")


class Checkers(unittest.TestCase):
    """check_week7.py on synthetic cdc.log files whose correct answer is known."""

    @classmethod
    def setUpClass(cls):
        if not w7.QUANT20.exists():
            raise unittest.SkipTest("SV3 quantization20 package not hydrated")

    def run_check(self, kind, lines, extra=()):
        session = Path(tempfile.mkdtemp(dir=TMP))
        (session / "cdc.log").write_text("".join(f"{i}\t{t}\n" for i, t in enumerate(lines)),
                                         encoding="utf-8")
        out = session / f"check_{kind}.json"
        code = subprocess.run([sys.executable, "-B", str(HERE / "check_week7.py"), kind,
                               "--session", str(session), "--output", str(out), *extra],
                              capture_output=True, text=True).returncode
        return code, __import__("json").loads(out.read_text(encoding="utf-8"))

    def verify_lines(self, corrupt=False):
        lines = ["READY WEEK7 build=x variant=energy-usb kernel=FAST split=2"]
        for n in range(20):
            g = w7.golden_tensor(n, 2)
            q_sha = g.q_sha256 if not (corrupt and n == 7) else "0" * 64
            lines.append(f"VQ n={n} s=2 C=16 L=180 q_sha256={q_sha} scale_sha256={g.scale_sha256}")
            plain = w7.build_request(n, 2, n + 1, None, None)
            lines.append(f"VREQ n={n} s=2 rho=P0 rid={n + 1} len={len(plain)} sha256={w7.sha256_hex(plain)}")
            p1 = w7.build_request(n, 2, n + 1, w7.PUBLIC_TEST_KEY, n + 1)
            lines.append(f"VREQ n={n} s=2 rho=P1 rid={n + 1} seq={n + 1} len={len(p1)} "
                         f"sha256={w7.sha256_hex(p1)} prot_us=1400")
        return lines + ["VERIFY END kernel=FAST"]

    def test_verify(self):
        code, report = self.run_check("verify", self.verify_lines())
        self.assertEqual(code, 0, report["checks"])
        code, report = self.run_check("verify", self.verify_lines(corrupt=True))
        self.assertEqual(code, 1)
        self.assertEqual(report["mismatches"], [{"n": 7, "s": 2, "what": "q/scale"}])

    def test_dryrun(self):
        lines = ["READY WEEK7 build=x variant=energy-usb kernel=FAST split=2",
                 "NONCE status=READY reason=NONE reserved_through=4096 next=4098 limit=5120"]
        for i in range(6):
            p1 = i < 3
            lines.append(f"CYCLE i={i} rho={'P1' if p1 else 'P0'} n={i} s=2 rid=0000000{i + 1} "
                         f"seq={4098 + i if p1 else 0} len={3116 if p1 else 3076} frags=14 mtu=247 "
                         f"ctrl_us=200 head_us=120000 quant_us=900 prot_us={1400 if p1 else 0} "
                         f"enc_us=4500 tx_us=90000 wait_us=60000 enomem=0 invalid=0 nonce_writes=0 "
                         f"status=0 res=OK")
        code, report = self.run_check("dryrun", lines, ["--p1", "3", "--p0", "3"])
        self.assertEqual(code, 0, report["checks"])
        lines[3] = lines[3].replace("nonce_writes=0", "nonce_writes=1")
        code, report = self.run_check("dryrun", lines, ["--p1", "3", "--p0", "3"])
        self.assertFalse(report["checks"]["no_flash_write_in_cycle"])

    def test_bench(self):
        hashes = TMP / "hashes.csv"
        write_head_hashes(hashes)
        rows = {}
        for line in hashes.read_text(encoding="utf-8").splitlines()[1:]:
            n, s, _, sha = line.split(",")
            rows[(int(n), int(s))] = sha
        lines = [f"CMP n={n} s={s} count=1 w4_sha256={rows[(n, s)]} equal=1"
                 for n in range(20) for s in range(11)] + ["CMP END pass=220 total=220"]
        lines += [f"MIX i={i} n={n} s={s} kernel={'FAST' if i % 2 else 'W4'} sha256={rows[(n, s)]} equal_ref=1"
                  for i, (n, s) in enumerate(MIXED)]
        for s in range(11):
            for kernel, cycles in (("W4", 1000 * (s + 1) * 3), ("FAST", 1000 * (s + 1))):
                lines += [f"CYCLES kernel={kernel} s={s} i={i} cycles={cycles}" for i in range(100)]
        code, report = self.run_check("bench", lines, ["--host-hashes", str(hashes)])
        self.assertEqual(code, 0, report["checks"])
        self.assertAlmostEqual(report["speedup_s10"], 3.0)


