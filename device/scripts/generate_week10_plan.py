#!/usr/bin/env python3
"""Week 10 plans (W10-D1, W10-D3, W10-D4), written into a new --output directory:

  ewait_load_blocks.csv   W10-D3 KV260 queue_sim scenario (duration_s, lambda_jobs_per_s): 40 s at 0, 18
                          blocks of 20 s (6 x {0, 15, 30} shuffled, seed 20261111), 60 s at 0. Must equal
                          the CSV sent to SV2 on 10/11 (SHA-256 38937e54...): checked.
  prot_plan.csv           W10-D1 radio-off E_prot session: 50 rounds x (10 P1/P0 pairs + 1 HEAD-only s1)
  week10_prot_plan.h      the 1050 (split, op) entries + WEEK10_PROT_PLAN_SHA256 (firmware `prot`)
  ble_plan.csv            W10-D4 radio-on session: 50 rounds x permutation of s0..s10, rho0, k0, natural payload
  week10_ble_plan.h       the 550 (split, rho, k, payload_bytes) entries + WEEK10_BLE_PLAN_SHA256 (firmware `ble`)
  manifest.json           seeds, counts, digests and their definitions, SHA-256 of every output
The outputs are deterministic (manifest.json aside: it records time and git state). Host only.
Run: device\\host\\.venv\\Scripts\\python.exe -B device\\scripts\\generate_week10_plan.py --output <new dir>
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import week10_common as w10  # noqa: E402

OUTPUTS = (w10.LOAD_CSV_NAME, "prot_plan.csv", "week10_prot_plan.h", "ble_plan.csv", "week10_ble_plan.h")


def prot_header(rows, digest: str) -> str:
    lines = ["/* GENERATED by device/scripts/generate_week10_plan.py - do not edit.",
             f" * W10-D1: {w10.ROUNDS} rounds; per round a random order (seed {w10.PROT_SEED}) of 10 P1/P0 pairs",
             " * (s0..s9, P1 first in even rounds) and one HEAD-only s1 cycle; round k uses W8-D3 sample k.",
             " * op: 0 = P0, 1 = P1, 2 = HEAD-only s1 (features.0 + ReLU, no quantization). */",
             "#ifndef WEEK10_PROT_PLAN_H", "#define WEEK10_PROT_PLAN_H", "#include <stdint.h>",
             f"#define WEEK10_PROT_PLAN_SEED {w10.PROT_SEED}U", f"#define WEEK10_PROT_PLAN_ROUNDS {w10.ROUNDS}U",
             f"#define WEEK10_PROT_PLAN_CYCLES {len(rows)}U",
             f"#define WEEK10_PROT_CYCLES_PER_ROUND {2 * w10.PROT_SPLITS + 1}U",
             f"#define WEEK10_OP_P0 {w10.OP_P0}U", f"#define WEEK10_OP_P1 {w10.OP_P1}U",
             f"#define WEEK10_OP_CONV {w10.OP_CONV}U",
             f'#define WEEK10_PROT_PLAN_SHA256 "{digest}"',
             "/* SHA-256 input: the bytes (split, op) of every cycle in order. */",
             "static const uint8_t week10_prot_plan[WEEK10_PROT_PLAN_CYCLES][2] = {"]
    per = 2 * w10.PROT_SPLITS + 1
    for k in range(w10.ROUNDS):
        chunk = rows[k * per:(k + 1) * per]
        lines.append("    " + ", ".join(f"{{{r.split}, {r.op}}}" for r in chunk) + f",   /* round {k} */")
    lines += ["};", "#endif", ""]
    return "\n".join(lines)


def ble_header(rows, digest: str) -> str:
    lines = ["/* GENERATED by device/scripts/generate_week10_plan.py - do not edit.",
             f" * W10-D4: {w10.ROUNDS} rounds x a permutation of s0..s10 (seed {w10.BLE_SEED}); round k uses W8-D3",
             " * sample k. rho 0 = rho0 (no protection), k = link state (0 = bench state), payload_bytes 0 =",
             " * the natural payload of the split; s10 runs the head and labels on the device (no TX/WAIT). */",
             "#ifndef WEEK10_BLE_PLAN_H", "#define WEEK10_BLE_PLAN_H", "#include <stdint.h>",
             f"#define WEEK10_BLE_PLAN_SEED {w10.BLE_SEED}U", f"#define WEEK10_BLE_PLAN_ROUNDS {w10.ROUNDS}U",
             f"#define WEEK10_BLE_PLAN_CYCLES {len(rows)}U", f"#define WEEK10_BLE_PLAN_SPLITS {w10.BLE_SPLITS}U",
             f'#define WEEK10_BLE_PLAN_SHA256 "{digest}"',
             "/* SHA-256 input: split, rho, k, payload_bytes (uint16 little-endian) = 5 bytes per cycle. */",
             "struct week10_ble_entry { uint8_t split; uint8_t rho; uint8_t k; uint16_t payload_bytes; };",
             "static const struct week10_ble_entry week10_ble_plan[WEEK10_BLE_PLAN_CYCLES] = {"]
    for k in range(w10.ROUNDS):
        chunk = rows[k * w10.BLE_SPLITS:(k + 1) * w10.BLE_SPLITS]
        lines.append("    " + ", ".join(f"{{{r.split}, {r.rho}, {r.k}, {r.payload_bytes}}}" for r in chunk)
                     + f",   /* round {k} */")
    lines += ["};", "#endif", ""]
    return "\n".join(lines)


def pairs_ok(prot) -> bool:
    """Every round: 11 runs of equal slot, each pair run = 2 cycles at split = slot in the round's order
    (P1, P0 when the round is even), the CONV run = 1 cycle at s1, every slot once."""
    per = 2 * w10.PROT_SPLITS + 1
    for k in range(w10.ROUNDS):
        chunk, runs = prot[k * per:(k + 1) * per], []
        for r in chunk:
            if runs and runs[-1][0].slot == r.slot:
                runs[-1].append(r)
            else:
                runs.append([r])
        want = (w10.OP_P1, w10.OP_P0) if k % 2 == 0 else (w10.OP_P0, w10.OP_P1)
        if sorted(run[0].slot for run in runs) != list(range(w10.PROT_SLOTS)):
            return False
        for run in runs:
            if run[0].slot == w10.PROT_SPLITS:
                if [(r.split, r.op) for r in run] != [(w10.CONV_SPLIT, w10.OP_CONV)]:
                    return False
            elif [(r.split, r.op) for r in run] != [(run[0].slot, want[0]), (run[0].slot, want[1])]:
                return False
    return True


def git_state() -> dict:
    def run(*args):
        return subprocess.run(["git", *args], cwd=w10.ROOT, capture_output=True, text=True, check=True).stdout.strip()
    sources = [p.relative_to(w10.ROOT).as_posix() for p in
               (Path(__file__).resolve(), HERE / "week10_common.py", HERE / "week9_common.py")]
    return {"head": run("rev-parse", "HEAD"), "status_of_generator_sources": run("status", "--short", "--", *sources)}


def generate(output: Path) -> dict:
    if output.exists():
        raise SystemExit("Use a new output directory")
    blocks = w10.load_blocks()
    prot, ble = w10.prot_plan(), w10.ble_plan()
    prot_sha, ble_sha = w10.sha256_hex(w10.prot_plan_bytes(prot)), w10.sha256_hex(w10.ble_plan_bytes(ble))
    per_round_prot = 2 * w10.PROT_SPLITS + 1
    prot_counts = Counter((r.split, r.op) for r in prot)
    ble_counts = Counter(r.split for r in ble)
    text = w10.load_csv_text(blocks)
    checks = {
        "load_csv_equals_sent_to_sv2": w10.sha256_hex(text.encode("utf-8")) == w10.LOAD_CSV_SHA256,
        "load_6_blocks_per_level": Counter(lv for d, lv in blocks[1:-1]) == {lv: 6 for lv in w10.LOAD_LEVELS},
        "load_total_460_s": sum(d for d, _ in blocks) == 460,
        "prot_cycles_1050": len(prot) == w10.PROT_CYCLES,
        "prot_50_p1_50_p0_per_split": all(prot_counts[(s, op)] == w10.ROUNDS
                                          for s in range(w10.PROT_SPLITS) for op in (w10.OP_P1, w10.OP_P0)),
        "prot_50_conv_s1": prot_counts[(w10.CONV_SPLIT, w10.OP_CONV)] == w10.ROUNDS,
        "prot_pairs_adjacent_and_alternating": pairs_ok(prot),
        "prot_round_k_uses_sample_k": all(r.sample == r.round == r.cycle // per_round_prot for r in prot),
        "ble_cycles_550": len(ble) == w10.BLE_CYCLES,
        "ble_50_per_split": all(ble_counts[s] == w10.ROUNDS for s in range(w10.BLE_SPLITS)),
        "ble_every_round_a_permutation": all(sorted(r.split for r in ble[k * 11:(k + 1) * 11]) == list(range(11))
                                             for k in range(w10.ROUNDS)),
        "ble_rho0_k0_natural": all((r.rho, r.k, r.payload_bytes) == (0, 0, 0) for r in ble),
        "ble_round_k_uses_sample_k": all(r.sample == r.round == r.cycle // w10.BLE_SPLITS for r in ble),
    }
    output.mkdir(parents=True)
    (output / w10.LOAD_CSV_NAME).write_bytes(text.encode("utf-8"))
    w10.write_prot_csv(output / "prot_plan.csv", prot)
    w10.write_ble_csv(output / "ble_plan.csv", ble)
    (output / "week10_prot_plan.h").write_bytes(prot_header(prot, prot_sha).encode("utf-8"))
    (output / "week10_ble_plan.h").write_bytes(ble_header(ble, ble_sha).encode("utf-8"))
    checks["csv_read_back"] = (w10.read_prot_csv(output / "prot_plan.csv") == prot
                               and w10.read_ble_csv(output / "ble_plan.csv") == ble
                               and w10.read_load_csv(output / w10.LOAD_CSV_NAME)
                               == [(float(d), float(lv)) for d, lv in blocks])
    status = "PASS" if all(checks.values()) else "FAIL"
    manifest = {
        "schema": "week10-plan/1", "status": status, "decisions": ["W10-D1", "W10-D3", "W10-D4"],
        "generator": "week10_common: splitmix64 + Fisher-Yates (week9_common), rejection sampling",
        "load": {"seed": w10.LOAD_SEED, "blocks": blocks, "csv_sha256": w10.LOAD_CSV_SHA256,
                 "definition": "shuffle of [0]*6 + [15]*6 + [30]*6; 40 s lead-in and 60 s tail at lambda 0"},
        "prot": {"seed": w10.PROT_SEED, "rounds": w10.ROUNDS, "cycles": len(prot), "plan_sha256": prot_sha,
                 "plan_sha256_definition": "SHA-256 of (split, op) bytes per cycle, op 0 P0 / 1 P1 / 2 CONV",
                 "first_round": [(r.split, w10.OP_NAMES[r.op]) for r in prot[:per_round_prot]]},
        "ble": {"seed": w10.BLE_SEED, "rounds": w10.ROUNDS, "cycles": len(ble), "plan_sha256": ble_sha,
                "plan_sha256_definition": "SHA-256 of (split, rho, k, payload_bytes uint16 LE) per cycle",
                "first_rounds": [[r.split for r in ble[k * 11:(k + 1) * 11]] for k in range(3)]},
        "checks": checks,
        "outputs_sha256": {n: w10.w8.w7.sha256_file(output / n) for n in OUTPUTS},
        "git": git_state(),
        "created_utc": datetime.now(timezone.utc).isoformat(),
    }
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", type=Path, required=True, help="new directory")
    manifest = generate(parser.parse_args().output.resolve())
    for name, ok in manifest["checks"].items():
        print(f"{'PASS' if ok else 'FAIL'} {name}")
    print(f"prot_plan_sha256={manifest['prot']['plan_sha256']}")
    print(f"ble_plan_sha256={manifest['ble']['plan_sha256']}")
    print(f"outputs_sha256={json.dumps(manifest['outputs_sha256'])}")
    print(f"RESULT: {manifest['status']}")
    return 0 if manifest["status"] == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
